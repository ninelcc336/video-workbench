/**
 * 中文注释：旧模板基线故意独立复制公开默认值，避免测试从注册表自身推导期望值。
 * 这些数据只允许在明确审阅视觉变化后更新，供后续特效族迁移保持 v1 行为。
 */
export type LegacyTemplateContract = {
  id: string;
  version: 1;
  category: TemplateCategory;
  name: string;
  defaultDurationInFrames: number;
  defaultParams: Record<string, unknown>;
  renderProps: TemplateRenderProps;
  renderFingerprint: string;
};

/** 中文注释：统一构造旧模板的固定帧输入，固定画幅、帧率和片段时长以便指纹可重复。 */
